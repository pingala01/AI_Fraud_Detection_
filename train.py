def log(msg):
    print(msg, flush=True)


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", help="CSV with the required columns (default: generate SYNTHETIC data)")
    p.add_argument("--rows", type=int, default=120_000, help="synthetic rows")
    p.add_argument("--fraud-rate", type=float, default=0.008)
    p.add_argument("--seed", type=int, default=C.RANDOM_STATE)
    p.add_argument("--n-iter", type=int, default=12, help="XGBoost random-search iterations")
    p.add_argument("--quick", action="store_true", help="small/fast settings for smoke tests")
    p.add_argument("--model-dir", default=str(C.MODEL_DIR))
    p.add_argument("--report-dir", default=str(C.REPORT_DIR))
    p.add_argument("--data-dir", default=str(C.DATA_DIR))
    return p.parse_args(argv)


def load_data(args):
    if args.data:
        df = pd.read_csv(args.data)
        missing = [c for c in C.RAW_COLUMNS + [C.TARGET] if c not in df.columns]
        if missing:
            raise SystemExit(f"Your CSV is missing required columns: {missing}")
        return df, f"user-supplied file: {args.data}"
    df = generate_synthetic_transactions(args.rows, args.fraud_rate, seed=args.seed)
    Path(args.data_dir).mkdir(parents=True, exist_ok=True)
    df.to_csv(Path(args.data_dir) / "synthetic_transactions.csv", index=False)
    return df, "SYNTHETIC (generated by src/data_generation.py) - not real bank data"


def chronological_split(df, train=0.70, val=0.15):
    n = len(df)
    i1, i2 = int(n * train), int(n * (train + val))
    return df.iloc[:i1], df.iloc[i1:i2], df.iloc[i2:]


# --------------------------------------------------------------------------- models
def fit_models(Xtr, ytr, args, skipped):
    q = args.quick
    seed = args.seed
    out = []

    def add(name, kind, model, t0, note=""):
        out.append({"name": name, "kind": kind, "model": model, "fit_seconds": time.time() - t0, "note": note})
        log(f"  fitted {name} in {time.time() - t0:.1f}s")

    log("Fitting models ...")
    t0 = time.time()
    add("logistic_regression", "proba",
        LogisticRegression(class_weight="balanced", max_iter=1000).fit(Xtr, ytr), t0,
        "baseline; class_weight='balanced' (cost-sensitive)")

    if SMOTE is not None:
        t0 = time.time()
        Xs, ys = SMOTE(sampling_strategy=0.1, random_state=seed).fit_resample(Xtr, ytr)
        add("logistic_regression_smote", "proba", LogisticRegression(max_iter=1000).fit(Xs, ys), t0,
            "SMOTE oversampling (fraud = 10% of normal) applied to training data only")
    else:
        skipped.append("SMOTE / logistic_regression_smote (imbalanced-learn not installed)")

    t0 = time.time()
    rf = RandomForestClassifier(n_estimators=50 if q else 150, max_depth=12, min_samples_leaf=5,
                                class_weight="balanced_subsample", n_jobs=-1, random_state=seed).fit(Xtr, ytr)
    add("random_forest", "proba", rf, t0, "baseline; balanced_subsample class weights")

    if xgb is not None:
        try:
            t0 = time.time()
            spw = float((ytr == 0).sum() / max((ytr == 1).sum(), 1))
            base = xgb.XGBClassifier(objective="binary:logistic", tree_method="hist", eval_metric="aucpr",
                                     n_jobs=-1, random_state=seed)
            dist = {"n_estimators": randint(60, 120) if q else randint(100, 400),
                    "max_depth": randint(3, 8), "learning_rate": loguniform(0.03, 0.3),
                    "subsample": uniform(0.6, 0.4), "colsample_bytree": uniform(0.6, 0.4),
                    "min_child_weight": randint(1, 10), "gamma": uniform(0, 2),
                    "reg_lambda": loguniform(0.5, 10),
                    "scale_pos_weight": [spw * 0.1, spw * 0.3, spw * 0.6, spw]}  # cost-sensitive weighting
            search = RandomizedSearchCV(base, dist, n_iter=3 if q else args.n_iter, scoring="average_precision",
                                        cv=StratifiedKFold(3, shuffle=True, random_state=seed),
                                        random_state=seed, n_jobs=1, refit=True, verbose=1)
            search.fit(Xtr, ytr)
            add("xgboost", "proba", search.best_estimator_, t0,
                f"tuned with RandomizedSearchCV (PR-AUC); best params: {search.best_params_}")
        except Exception:
            traceback.print_exc()
            skipped.append("xgboost (training failed - see traceback above)")
    else:
        skipped.append("XGBoost (xgboost not installed)")

    t0 = time.time()
    iso = IsolationForest(n_estimators=100 if q else 200, random_state=seed, n_jobs=-1).fit(Xtr)
    add("isolation_forest", "isolation_forest", iso, t0, "advanced/optional: unsupervised, ignores labels")

    t0 = time.time()
    rng = np.random.default_rng(seed)
    legit = Xtr[ytr == 0]
    legit = legit[rng.choice(len(legit), size=min(len(legit), 40_000), replace=False)]
    ae = MLPRegressor(hidden_layer_sizes=(16, 8, 16), max_iter=15 if q else 60, early_stopping=True,
                      n_iter_no_change=5, random_state=seed).fit(legit, legit)
    add("autoencoder", "autoencoder", ae, t0,
        "advanced/optional: shallow autoencoder (scikit-learn MLPRegressor) trained on normal rows only")
    return out


# --------------------------------------------------------------------------- reports
def save_pr_plot(results, yte, Xte, report_dir):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(7, 5))
        for r in results:
            s = raw_scores(r["kind"], r["model"], Xte)
            p, rc, _ = precision_recall_curve(yte, s)
            ax.plot(rc, p, label=f"{r['name']} (AP={r['test']['pr_auc']:.2f})")
        ax.set_xlabel("Recall"); ax.set_ylabel("Precision"); ax.set_title("Precision-recall curves (test set)")
        ax.legend(fontsize=8); ax.grid(alpha=0.3)
        fig.tight_layout(); fig.savefig(Path(report_dir) / "pr_curves.png", dpi=120); plt.close(fig)
    except Exception as exc:
        log(f"  (PR plot skipped: {exc})")


def shap_report(sel, Xte, Xbg, names, report_dir, quick, skipped):
    if shap is None:
        skipped.append("SHAP (shap not installed)")
        return None
    if explain_family(sel["name"]) is None:
        skipped.append(f"SHAP (not supported for selected model '{sel['name']}')")
        return None
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from .explain import build_explainer, shap_values, units_for
        n = 300 if quick else 1000
        idx = np.random.default_rng(0).choice(len(Xte), size=min(n, len(Xte)), replace=False)
        Xs = Xte[idx]
        ex = build_explainer(sel["model"], sel["name"], Xbg)
        sv, _ = shap_values(ex, Xs)
        imp = np.abs(sv).mean(axis=0)
        top = sorted(zip(names, imp), key=lambda t: -t[1])[:20]
        data = {"method": ex[0], "units": units_for(sel["name"]), "rows_explained": int(len(Xs)),
                "mean_abs_shap_top20": {k: float(v) for k, v in top}}
        for kind, fname in (("bar", "shap_importance_bar.png"), ("dot", "shap_summary.png")):
            plt.figure()
            shap.summary_plot(sv, Xs, feature_names=names, plot_type=kind, show=False, max_display=15)
            plt.tight_layout(); plt.savefig(Path(report_dir) / fname, dpi=120, bbox_inches="tight"); plt.close()
        return data
    except Exception:
        traceback.print_exc()
        skipped.append("SHAP report (failed - see traceback above)")
        return None


def measure_latency(model_path, test_raw, n, seed):
    from .predictor import FraudPredictor
    pred = FraudPredictor(model_path)
    recs = test_raw[C.RAW_COLUMNS].sample(min(n + 30, len(test_raw)), random_state=seed).to_dict("records")
    for r in recs[:30]:
        pred.predict_one(r)  # warm-up
    times = []
    for r in recs[30:]:
        t = time.perf_counter(); pred.predict_one(r); times.append((time.perf_counter() - t) * 1000)
    a = np.array(times)
    return {"n_requests": int(len(a)), "mean_ms": float(a.mean()), "p50_ms": float(np.percentile(a, 50)),
            "p95_ms": float(np.percentile(a, 95)), "p99_ms": float(np.percentile(a, 99)), "max_ms": float(a.max()),
            "scope": "in-process, single transaction, 1 CPU thread; excludes HTTP/network overhead"}


def lib_versions():
    out = {}
    for pkg in ["numpy", "pandas", "scikit-learn", "scipy", "xgboost", "shap", "imbalanced-learn", "joblib"]:
        try:
            out[pkg] = metadata.version(pkg)
        except metadata.PackageNotFoundError:
            out[pkg] = "not installed"
    return out


def write_results_md(path, m):
    t = m["selected_test_metrics"]; lat = m["latency"]; tg = m["targets_met"]
    yn = lambda v: "n/a" if v is None else ("YES" if v else "NO")
    lines = [
        "# Model evaluation results (auto-generated by src/train.py)", "",
        f"- Trained at: {m['trained_at']}", f"- Data source: {m['data']['source']}",
        f"- Rows: {m['data']['rows']:,}; fraud rate: {m['data']['fraud_rate']:.3%}",
        f"- Split (chronological): train {m['split']['train']:,} / validation {m['split']['val']:,} / test {m['split']['test']:,}",
        f"- Test frauds: {t['tp'] + t['fn']}; test normal transactions: {t['fp'] + t['tn']:,}",
        f"- Cost assumptions (illustrative): missed fraud = {m['costs']['false_negative']}, false alert = {m['costs']['false_positive']}",
        f"- Selected model: **{m['selected_model']}** (chosen on VALIDATION data, reported on TEST data)", "",
        "## Model comparison (test set, threshold chosen on validation set)", "",
        "| Model | Recall | FPR | Precision | PR-AUC | ROC-AUC | Cost | Threshold |",
        "|---|---|---|---|---|---|---|---|"]
    for r in m["models"]:
        x = r["test"]
        lines.append(f"| {r['name']} | {x['recall']:.3f} | {x['fpr']:.3%} | {x['precision']:.3f} | "
                     f"{x['pr_auc']:.3f} | {x['roc_auc']:.3f} | {x['cost']:.0f} | {x['threshold']:.4f} |")
    lines += ["", "## Targets from the project guide (measured on the test set)", "",
              "| Target | Measured | Met? |", "|---|---|---|",
              f"| Fraud recall > {C.TARGET_RECALL:.0%} | {t['recall']:.1%} (95% CI {t['recall_ci95'][0]:.1%}-{t['recall_ci95'][1]:.1%}) | {yn(tg['recall'])} |",
              f"| False positive rate < {C.TARGET_FPR:.0%} | {t['fpr']:.2%} (95% CI {t['fpr_ci95'][0]:.2%}-{t['fpr_ci95'][1]:.2%}) | {yn(tg['fpr'])} |",
              f"| Latency < {C.TARGET_LATENCY_MS:.0f} ms | p50 {lat['p50_ms']:.1f} / p95 {lat['p95_ms']:.1f} / p99 {lat['p99_ms']:.1f} ms | {yn(tg['latency_p99'])} (judged on p99) |",
              "", f"Latency scope: {lat['scope']}.", "",
              f"Cost saving vs flagging nothing (under the assumed costs): {t['cost_saving_vs_flag_nothing']:.1%}.", "",
              f"Baseline drift check (validation vs test, no real drift expected): max PSI = {m['drift_baseline_max_psi']:.3f}.", ""]
    if m["skipped_components"]:
        lines += ["## SKIPPED components in this run", ""] + [f"- {s}" for s in m["skipped_components"]] + [""]
    lines += ["## Caveats", "",
              "- Synthetic data results do not predict real-world performance.",
              "- The test set contains few fraud cases, so recall has a wide confidence interval.",
              "- Thresholds and costs depend on the assumed cost values; change them in src/config.py.", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8")


# --------------------------------------------------------------------------- main
def main(argv=None):
    args = parse_args(argv)
    model_dir, report_dir = Path(args.model_dir), Path(args.report_dir)
    model_dir.mkdir(parents=True, exist_ok=True); report_dir.mkdir(parents=True, exist_ok=True)
    skipped = []

    df, source = load_data(args)
    df = df.copy()
    df["timestamp"] = pd.to_datetime(df["timestamp"])
    df = df.sort_values("timestamp").reset_index(drop=True)
    log(f"Data: {len(df):,} rows, fraud rate {df[C.TARGET].mean():.3%}  [{source}]")
    tr, va, te = chronological_split(df)
    for nm, part in (("train", tr), ("validation", va), ("test", te)):
        if part[C.TARGET].sum() < 10:
            raise SystemExit(f"The {nm} split has fewer than 10 fraud cases - use more rows or a higher fraud rate.")

    feats = [add_features(p) for p in (tr, va, te)]
    pre = build_preprocessor().fit(feats[0])
    Xtr, Xva, Xte = (pre.transform(f) for f in feats)
    ytr, yva, yte = (p[C.TARGET].to_numpy().astype(int) for p in (tr, va, te))
    names = clean_names(pre.get_feature_names_out())

    models = fit_models(Xtr, ytr, args, skipped)

    log("Choosing thresholds (validation) and evaluating (test) ...")
    c_fn, c_fp = C.COST_FALSE_NEGATIVE, C.COST_FALSE_POSITIVE
    for r in models:
        sv_ = raw_scores(r["kind"], r["model"], Xva)
        thr = choose_threshold(yva, sv_, c_fn, c_fp, C.THRESHOLD_FPR_CAP)
        r["val_scores"] = sv_
        r["val"] = evaluate_scores(yva, sv_, thr, c_fn, c_fp)
        r["test"] = evaluate_scores(yte, raw_scores(r["kind"], r["model"], Xte), thr, c_fn, c_fp)

    eligible = [r for r in models if r["val"]["recall"] > C.TARGET_RECALL and r["val"]["fpr"] < C.TARGET_FPR]
    pool = eligible or models
    sel = min(pool, key=lambda r: r["val"]["cost"])
    if not eligible:
        skipped.append("NOTE: no model met the recall/FPR targets on the validation set; the lowest-cost model was selected")
    log(f"Selected model: {sel['name']}")

    # ---- save bundle + reference sample for drift monitoring
    vs = sel["val_scores"]
    bg = Xtr[np.random.default_rng(args.seed).choice(len(Xtr), size=min(200, len(Xtr)), replace=False)]
    bundle = {"preprocessor": pre, "model": sel["model"], "model_name": sel["name"], "score_kind": sel["kind"],
              "threshold": sel["val"]["threshold"], "feature_names": names, "background": bg,
              "score_lo": float(np.percentile(vs, 1)), "score_hi": float(np.percentile(vs, 99.9)),
              "trained_at": datetime.now(timezone.utc).isoformat(), "library_versions": lib_versions()}
    model_path = model_dir / C.MODEL_FILENAME
    joblib.dump(bundle, model_path)
    ref = va[C.RAW_COLUMNS].copy()
    ref["score"] = vs
    ref.sample(min(5000, len(ref)), random_state=args.seed).to_csv(model_dir / C.REFERENCE_FILENAME, index=False)

    shap_data = shap_report(sel, Xte, bg, names, report_dir, args.quick, skipped)
    save_pr_plot(models, yte, Xte, report_dir)
    latency = measure_latency(model_path, te, 100 if args.quick else 300, args.seed)
    base_drift = drift_report(va[C.RAW_COLUMNS], te[C.RAW_COLUMNS])

    t = sel["test"]
    metrics = {
        "trained_at": bundle["trained_at"], "python": platform.python_version(), "platform": platform.platform(),
        "library_versions": lib_versions(),
        "data": {"source": source, "rows": int(len(df)), "fraud_rate": float(df[C.TARGET].mean())},
        "split": {"train": len(tr), "val": len(va), "test": len(te)},
        "costs": {"false_negative": c_fn, "false_positive": c_fp, "threshold_fpr_cap": C.THRESHOLD_FPR_CAP},
        "targets": {"recall_gt": C.TARGET_RECALL, "fpr_lt": C.TARGET_FPR, "latency_ms_lt": C.TARGET_LATENCY_MS},
        "models": [{"name": r["name"], "kind": r["kind"], "note": r["note"], "fit_seconds": r["fit_seconds"],
                    "val": r["val"], "test": r["test"]} for r in models],
        "selected_model": sel["name"], "selected_test_metrics": t,
        "targets_met": {"recall": t["recall"] > C.TARGET_RECALL, "fpr": t["fpr"] < C.TARGET_FPR,
                        "latency_p99": latency["p99_ms"] < C.TARGET_LATENCY_MS},
        "latency": latency, "shap": shap_data,
        "drift_baseline_max_psi": base_drift["max_psi"], "skipped_components": skipped,
    }
    (report_dir / "metrics.json").write_text(json.dumps(metrics, indent=2, default=float), encoding="utf-8")
    rows = [{"model": r["name"], **{f"test_{k}": r["test"][k] for k in ("recall", "fpr", "precision", "f1", "pr_auc", "roc_auc", "cost", "threshold")},
             "val_cost": r["val"]["cost"]} for r in models]
    pd.DataFrame(rows).to_csv(report_dir / "model_comparison.csv", index=False)
    write_results_md(report_dir / "RESULTS.md", metrics)

    log("\n" + pd.DataFrame(rows).drop(columns=["val_cost"]).round(4).to_string(index=False))
    log(f"\nSelected: {sel['name']} | test recall {t['recall']:.1%} | test FPR {t['fpr']:.2%} | "
        f"latency p99 {latency['p99_ms']:.1f} ms")
    log(f"Targets met -> recall: {metrics['targets_met']['recall']}, FPR: {metrics['targets_met']['fpr']}, "
        f"latency(p99): {metrics['targets_met']['latency_p99']}")
    if skipped:
        log("SKIPPED / NOTES:\n  - " + "\n  - ".join(skipped))
    log(f"Saved model to {model_path} and reports to {report_dir}")
    return metrics


if __name__ == "__main__":
    main()
